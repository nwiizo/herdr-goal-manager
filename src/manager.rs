//! Native conversation entrypoint. Provider history stays with the provider.
use crate::{binding::Existing, herdr_cli as herdr, store::Store, supervision};
use anyhow::{Context, Result, bail, ensure};
use clap::ValueEnum;
use std::{ffi::OsString, path::Path, process::Command};

#[derive(Debug, Clone, Copy, PartialEq, Eq, ValueEnum)]
pub(crate) enum Provider {
    Codex,
    Claude,
    Copilot,
}
impl Provider {
    pub fn name(self) -> &'static str {
        match self {
            Self::Codex => "codex",
            Self::Claude => "claude",
            Self::Copilot => "copilot",
        }
    }
    /// The provider's allow-everything flag. Agents hgm launches (managers, impl
    /// and reviewer) run with it by user decision so they never stall on a
    /// permission prompt; the user's own main session keeps its options.
    pub(crate) fn full_access_args(self) -> &'static [&'static str] {
        match self {
            Self::Codex => &["--dangerously-bypass-approvals-and-sandbox"],
            Self::Claude => &["--dangerously-skip-permissions"],
            Self::Copilot => &["--allow-all"],
        }
    }
}
/// Starts the native manager conversation. `reference` is the CLI command list,
/// generated by `cli` so this module does not depend on the CLI definition.
pub(crate) async fn launch(
    store: &Store,
    provider: Option<Provider>,
    model: Option<&str>,
    reference: &str,
) -> Result<()> {
    let config = crate::config::load(&store.workspace)?;
    let context = crate::binding::prepare_context(store)?;
    let provider = match provider {
        Some(provider) => provider,
        None => choose_provider(
            context.origin.as_ref().and_then(|o| o.agent.as_deref()),
            std::env::var("HGM_AGENT")
                .ok()
                .as_deref()
                .or(config.agent.as_deref()),
        )?,
    };
    let model = model.or(config.model(provider.name()));
    // Reopened for the same tab: take over its running watch, so wakes reach
    // this manager instead of a closed one.
    if let Ok(pane) = std::env::var("HERDR_PANE_ID")
        && let Ok(live) = supervision::live_pane(&pane).await
        && let Ok(mut manager) = supervision::Target::from_value(&live)
    {
        // One Goal Manager per tab, even when two opens race: the check and the
        // registration hold the tab's launch lease, and a manager registered
        // moments ago counts as running before Herdr shows its agent.
        let _launch = match &context.origin {
            Some(origin) => {
                Some(crate::binding::launch_lease(&store.root, &origin.terminal).await?)
            }
            None => None,
        };
        if let Some(origin) = &context.origin {
            match crate::binding::existing_manager(&store.root, origin).await? {
                Some(Existing::Manager(other)) if other.terminal != manager.terminal => {
                    herdr::call(&["tab".into(), "focus".into(), other.tab.clone()]).await?;
                    bail!(
                        "Goal Manager is already open for this tab (pane {}); switched to it",
                        other.pane
                    );
                }
                Some(Existing::Helper(role)) => {
                    bail!("this tab runs the {role} helper; open Goal Manager from the main tab")
                }
                _ => {}
            }
        }
        manager.agent = Some(provider.name().into());
        manager.session = None;
        crate::binding::register_manager(store, &context, &manager)?;
        match crate::watch::adopt_watch(store, &context.key(), manager) {
            Ok(Some(goal)) => eprintln!("Took over the running watch of goal {goal}."),
            Ok(None) => {}
            Err(error) => eprintln!("Could not take over the running watch: {error:#}"),
        }
    }
    crate::binding::save_context(store, &context)?;
    let opener = config.opener();
    let directory = store.private_directory("manager")?;
    let draft_dir = directory.join("drafts");
    std::fs::create_dir_all(&draft_dir)?;
    let guide = format!("{}\n\n{reference}\n", config.guide());
    let executable = std::env::current_exe()?.canonicalize()?;
    let search_path = manager_path(&directory, &context.id, &executable)?;
    let mut command = Command::new(provider.name());
    command.args(provider.full_access_args());
    if let Some(model) = model {
        command.args(["--model", model]);
    }
    command
        .env_remove("CODEX_THREAD_ID")
        .current_dir(&store.workspace)
        .env("PATH", &search_path)
        .env("HGM_BIN", &executable)
        .env("HGM_WORKSPACE", &store.workspace)
        .env("HGM_STATE_DIR", &store.root)
        .env("HGM_CONTEXT", &context.id)
        .env("HGM_DRAFT_DIR", &draft_dir);
    match provider {
        Provider::Codex => {
            command.arg("--no-daemon");
            let environment = [
                ("PATH", search_path.to_string_lossy().into_owned()),
                ("HGM_BIN", executable.display().to_string()),
                ("HGM_WORKSPACE", store.workspace.display().to_string()),
                ("HGM_STATE_DIR", store.root.display().to_string()),
                ("HGM_CONTEXT", context.id.clone()),
                ("HGM_DRAFT_DIR", draft_dir.display().to_string()),
            ];
            command.args(["-c", &codex_environment(&environment)?]);
            command.args([
                "-c",
                &format!("developer_instructions={}", serde_json::to_string(&guide)?),
            ]);
            command.arg("--add-dir").arg(&store.root).arg(opener);
        }
        Provider::Copilot => {
            // Copilot has no system-prompt flag; it loads path-scoped instructions from
            // COPILOT_CUSTOM_INSTRUCTIONS_DIRS, so the guide is not the first user turn.
            let instructions = directory.join(format!("{}-copilot", context.id));
            let rules = instructions.join(".github/instructions");
            std::fs::create_dir_all(&rules)?;
            std::fs::write(
                rules.join("hgm-manager.instructions.md"),
                format!("---\napplyTo: \"**\"\n---\n{guide}"),
            )
            .context("write Copilot manager instructions")?;
            let mut directories = instructions.display().to_string();
            if let Ok(existing) = std::env::var("COPILOT_CUSTOM_INSTRUCTIONS_DIRS")
                && !existing.is_empty()
            {
                directories = format!("{existing},{directories}");
            }
            command
                .env("COPILOT_CUSTOM_INSTRUCTIONS_DIRS", directories)
                .arg("--add-dir")
                .arg(&store.root)
                .args(["--interactive", opener]);
        }
        Provider::Claude => {
            let settings = directory.join(format!("{}-hooks.json", context.id));
            let hook = |name: &str| {
                format!(
                    "{} --workspace {} --state-dir {} {name}",
                    quote(executable.as_os_str()),
                    quote(store.workspace.as_os_str()),
                    quote(store.root.as_os_str())
                )
            };
            // Idle compaction would summarize the manager between wakes for no
            // reason; automatic compaction near a full context stays on, and the
            // SessionStart hook restores saved state after it.
            let mut settings_value = serde_json::json!({
                "idleCompaction": false,
                "hooks": {
                    "Stop":[{"hooks":[{"type":"command","command":hook("hook-stop"),"timeout":10}]}],
                    "SessionStart":[{"matcher":"compact|resume|clear","hooks":[{"type":"command","command":hook("hook-session"),"timeout":10}]}],
                },
            });
            // The manager drives Herdr through its CLI, which connects to Herdr's
            // socket. Claude Code's sandbox refuses Unix sockets it does not list,
            // so allow exactly this one; the rest of the sandbox stays as configured.
            if let Some(socket) = std::env::var_os("HERDR_SOCKET_PATH") {
                settings_value["sandbox"] = serde_json::json!({
                    "network": {"allowUnixSockets": [socket.to_string_lossy()]},
                });
            }
            store.write_private(&settings, &settings_value)?;
            command
                .args(["--add-dir"])
                .arg(&store.root)
                .args(["--settings"])
                .arg(settings)
                .arg("--append-system-prompt")
                .arg(&guide)
                .arg(opener);
        }
    }
    if std::env::var("HGM_PLUGIN_PANEL").as_deref() == Ok("1") {
        herdr::present_current_tab("Goal Manager").await?;
    }
    eprintln!(
        "Goal Manager · {} · {}\nTalk normally. Decisions survive in the brief; tracked work is available with hgm status.",
        provider.name(),
        store.workspace.display()
    );
    exec(command).with_context(|| {
        format!(
            "start {}; install/authenticate that CLI, or choose --agent claude/codex/copilot",
            provider.name()
        )
    })
}
#[cfg(unix)]
fn exec(mut command: Command) -> Result<()> {
    use std::os::unix::process::CommandExt;
    Err(command.exec().into())
}
#[cfg(not(unix))]
fn exec(mut command: Command) -> Result<()> {
    ensure!(command.status()?.success(), "agent exited unsuccessfully");
    Ok(())
}
/// The manager talks through the original tab's client: Codex for Codex, Claude
/// Code for Claude Code, Copilot for Copilot. `HGM_AGENT` covers a shell or
/// unsupported tab; Codex is the last resort.
fn choose_provider(origin: Option<&str>, configured: Option<&str>) -> Result<Provider> {
    if let Some(provider) = origin.and_then(|agent| Provider::from_str(agent, true).ok()) {
        return Ok(provider);
    }
    match configured {
        Some(name) => Provider::from_str(name, true).map_err(|_| {
            anyhow::anyhow!("HGM_AGENT must be claude, codex, or copilot, got {name}")
        }),
        None => Ok(Provider::Codex),
    }
}
/// Builds the manager's PATH with this exact build first, as plain `hgm`, so
/// agents run (and providers can pre-approve) `hgm ...` instead of a long path.
/// Codex's shell tool gets its environment from config, not from the process
/// (a shared daemon may hold another terminal's): pass hgm and Herdr variables.
pub(crate) fn codex_environment(pairs: &[(&str, String)]) -> Result<String> {
    let mut environment: std::collections::BTreeMap<String, String> = pairs
        .iter()
        .map(|(key, value)| (key.to_string(), value.clone()))
        .collect();
    for name in [
        "HERDR_ENV",
        "HERDR_SOCKET_PATH",
        "HERDR_PANE_ID",
        "HERDR_TAB_ID",
        "HERDR_WORKSPACE_ID",
        "HERDR_BIN_PATH",
    ] {
        if let Ok(value) = std::env::var(name) {
            environment.entry(name.into()).or_insert(value);
        }
    }
    let fields = environment
        .into_iter()
        .map(|(key, value)| Ok(format!("{key}={}", serde_json::to_string(&value)?)))
        .collect::<Result<Vec<_>>>()?;
    Ok(format!(
        "shell_environment_policy.set={{{}}}",
        fields.join(",")
    ))
}
pub(crate) fn manager_path(directory: &Path, context: &str, executable: &Path) -> Result<OsString> {
    let bin = directory.join(format!("{context}-bin"));
    std::fs::create_dir_all(&bin)?;
    if std::fs::symlink_metadata(bin.join("hgm")).is_err() {
        link_hgm(executable, &bin)?;
    }
    let inherited = std::env::var_os("PATH").unwrap_or_default();
    std::env::join_paths(std::iter::once(bin).chain(std::env::split_paths(&inherited)))
        .context("build the manager PATH")
}
#[cfg(unix)]
fn link_hgm(executable: &Path, bin: &Path) -> Result<()> {
    std::os::unix::fs::symlink(executable, bin.join("hgm")).context("expose hgm to the manager")
}
#[cfg(not(unix))]
fn link_hgm(executable: &Path, bin: &Path) -> Result<()> {
    std::fs::copy(executable, bin.join("hgm.exe"))
        .map(|_| ())
        .context("expose hgm to the manager")
}
/// Single-quotes `value` for `/bin/sh`.
pub(crate) fn quote(value: &std::ffi::OsStr) -> String {
    format!("'{}'", value.to_string_lossy().replace('\'', "'\\''"))
}
pub(crate) fn save_brief(store: &Store, scope: Option<&str>, file: &Path) -> Result<String> {
    use std::io::Read;
    let mut text = String::new();
    if file == Path::new("-") {
        std::io::stdin().take(131_073).read_to_string(&mut text)?;
    } else {
        text = std::fs::read_to_string(file).context("read brief")?;
    }
    ensure!(!text.trim().is_empty(), "brief must not be empty");
    ensure!(text.len() <= 131_072, "brief exceeds 128 KiB");
    store.save_brief(scope, &text)?;
    Ok(text)
}
pub(crate) fn stdin_json() -> Result<serde_json::Value> {
    use std::io::Read;
    let mut text = String::new();
    std::io::stdin().take(131_073).read_to_string(&mut text)?;
    if text.len() > 131_072 {
        bail!("hook input too large");
    }
    Ok(serde_json::from_str(&text)?)
}
